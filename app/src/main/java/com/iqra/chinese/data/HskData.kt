    fun wordById(id: String) = words.values.flatten().find { it.id == id }

    /** Flat index of every word's exact character text → Word, built once.
     *  When the same text exists at multiple levels, the LOWEST level wins
     *  (levels map is iterated 1→6 in order, first match kept). */
    private val wordsByChar: Map<String, Word> by lazy {
        val result = LinkedHashMap<String, Word>()
        for (lvl in 1..6) {
            for (w in words[lvl] ?: emptyList()) {
                if (!result.containsKey(w.char)) result[w.char] = w
            }
        }
        result
    }

    private val maxWordLen: Int by lazy { wordsByChar.keys.maxOfOrNull { it.length } ?: 1 }

    fun wordByChar(char: String): Word? = wordsByChar[char]

    /**
     * Greedy longest-match segmentation: walks the sentence left to right,
     * at each position trying the longest known word first (down to 1
     * character), matching against the SAME word list already shown
     * elsewhere in the app. Characters that match no known word (mostly
     * punctuation, or vocabulary outside the current word list) are simply
     * skipped — no separate/duplicate word list is introduced.
     */
    fun segmentSentence(text: String): List<Word> {
        val result = mutableListOf<Word>()
        var i = 0
        while (i < text.length) {
            var matched = false
            var len = minOf(maxWordLen, text.length - i)
            while (len >= 1) {
                val candidate = text.substring(i, i + len)
                val w = wordsByChar[candidate]
                if (w != null) {
                    result.add(w)
                    i += len
                    matched = true
                    break
                }
                len--
            }
            if (!matched) i += 1
        }
        return result
    }

